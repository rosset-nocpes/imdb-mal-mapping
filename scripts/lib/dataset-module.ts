import { writeFile } from "node:fs/promises";
import type { Index } from "../../src/types.js";

/** src/dataset.ts: the index as a string parsed on first use, plus its content hash. */
export class DatasetModule {
  constructor(readonly index: Index) {}

  /** Ignores the build time, so unchanged data never triggers a release. */
  get hash(): string {
    return new Bun.CryptoHasher("sha256")
      .update(JSON.stringify(this.index.anime))
      .digest("hex")
      .slice(0, 16);
  }

  render(): string {
    // A string parsed on first use loads faster than an object literal.
    return [
      "// Generated by scripts/build-index.ts. Do not edit.",
      `export const hash: string = "${this.hash}";`,
      `const data: string = ${JSON.stringify(JSON.stringify(this.index))};`,
      "export default data;",
      "",
    ].join("\n");
  }

  async write(path: string): Promise<void> {
    await writeFile(path, this.render());
  }
}
